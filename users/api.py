# ==================== Change Password (OTP-Verified) ====================


@router.post(
    "/change-password/",
    auth=BearerAuth(),
    response={200: MessageOut, 401: MessageOut, 429: MessageOut},
)
async def change_password(request, payload: ChangePasswordIn):
    """
    Step 1 of password change: Verify current password, then send OTP.
    Returns a message — user must call /change-password/confirm/ next.
    """
    user = request.user

    if not await user.acheck_password(payload.current_password):
        return 401, {"message": "Current password is incorrect."}

    try:
        from .services import create_and_send_otp

        await create_and_send_otp(user.email, "change_password", user=user)
    except ValueError as e:
        return 429, {"message": str(e)}

    return 200, {"message": "OTP sent to your email for password change verification."}


@router.post(
    "/change-password/confirm/",
    auth=BearerAuth(),
    response={200: MessageOut, 401: MessageOut},
)
async def change_password_confirm(request, payload: ChangePasswordConfirmIn):
    """
    Step 2 of password change: Verify OTP and set new password.
    """
    from .services import verify_otp

    user = request.user

    # Ensure the OTP email matches the authenticated user
    if payload.email != user.email:
        return 401, {"message": "Email does not match authenticated user."}

    try:
        await verify_otp(payload.email, payload.otp, "change_password")
    except ValueError as e:
        return 401, {"message": str(e)}

    # Set new password
    user.set_password(payload.new_password)
    await user.asave(update_fields=["password", "updated_at"])

    return 200, {"message": "Password changed successfully."}


# ==================== Forgot Password (OTP-Verified, Unauthenticated) ====================


@router.post(
    "/forgot-password/",
    response={200: MessageOut, 401: MessageOut, 429: MessageOut},
)
async def forgot_password(request, payload: ForgotPasswordIn):
    """
    Step 1 of forgot password: Validate email exists and is active, then send OTP.
    Returns a message — user must call /forgot-password/confirm/ next.

    NOTE: Always returns 200 for valid emails to prevent email enumeration.
    """
    try:
        user = await User.objects.aget(email=payload.email, is_active=True)
    except User.DoesNotExist:
        # Don't reveal whether email exists — return same message
        return 200, {
            "message": "If this email is registered, you will receive a verification code."
        }

    try:
        from .services import create_and_send_otp

        await create_and_send_otp(user.email, "forgot_password", user=user)
    except ValueError as e:
        return 429, {"message": str(e)}

    return 200, {
        "message": "If this email is registered, you will receive a verification code."
    }


@router.post(
    "/forgot-password/confirm/",
    response={200: MessageOut, 401: MessageOut},
)
async def forgot_password_confirm(request, payload: ForgotPasswordConfirmIn):
    """
    Step 2 of forgot password: Verify OTP and set new password.
    Unauthenticated — user proves identity via OTP.
    """
    from .services import verify_otp

    # Verify the OTP
    try:
        await verify_otp(payload.email, payload.otp, "forgot_password")
    except ValueError as e:
        return 401, {"message": str(e)}

    # Look up user and set new password
    try:
        user = await User.objects.aget(email=payload.email, is_active=True)
    except User.DoesNotExist:
        return 401, {"message": "No active account found with this email."}

    user.set_password(payload.new_password)
    await user.asave(update_fields=["password", "updated_at"])

    return 200, {
        "message": "Password reset successfully. You can now log in with your new password."
    }
