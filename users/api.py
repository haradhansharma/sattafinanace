"""
Auth API for FinLife.
OTP-based email verification for registration, login, and password changes.

Flow:
  Register          → OTP sent to email → Verify OTP → Tokens returned (account activated)
  Login             → Validate credentials → OTP sent → Verify OTP → Tokens returned
  Forgot Password   → Enter email → OTP sent → Verify OTP + New Password → Password reset
  Change Password   → Verify current password → OTP sent → Verify OTP → Password changed
"""

from django.contrib.auth import get_user_model
from django.db import IntegrityError
from ninja import Router

from common.permissions import BearerAuth
from .schemas import (
    ChangePasswordConfirmIn,
    ChangePasswordIn,
    ForgotPasswordConfirmIn,
    ForgotPasswordIn,
    MessageOut,
    NotificationPreferenceSchema,
    OTPVerifyIn,
    RefreshTokenIn,
    RefreshTokenOut,
    ResendOtpIn,
    TokenOut,
    UserCreate,
    UserLogin,
    UserOut,
    UserUpdate,
)

User = get_user_model()
router = Router(tags=["Auth"])


# ==================== Registration ====================


@router.post("/register/", response={201: MessageOut, 400: MessageOut})
async def register(request, payload: UserCreate):
    """
    Register a new user and send email verification OTP.
    Account is INACTIVE until OTP is verified.
    Returns a message — NOT tokens.
    """
    if await User.objects.filter(email=payload.email).aexists():
        return 400, {"message": "Email already registered."}

    try:
        user = await User.objects.acreate_user(
            email=payload.email,
            password=payload.password,
            name=payload.name,
            currency=payload.currency,
            date_format=payload.dateFormat,
            dark_mode=payload.darkMode,
        )
        # slug (UUID) is auto-generated by Django default=uuid.uuid4
    except (ValueError, IntegrityError) as e:
        return 400, {"message": str(e)}

    # Send verification OTP
    try:
        from .services import create_and_send_otp

        await create_and_send_otp(user.email, "register", user=user)
    except ValueError as e:
        return 400, {"message": str(e)}

    return 201, {
        "message": "Registration successful! Please check your email for a verification code."
    }


# ==================== Verify OTP ====================


@router.post("/verify-otp/", response={200: TokenOut, 401: MessageOut})
async def verify_otp_endpoint(request, payload: OTPVerifyIn):
    """
    Verify OTP code for registration or login.
    On success: activates account (if register) and returns JWT tokens.

    NOTE: change_password and forgot_password purposes are handled by their
    own confirm endpoints — this endpoint only issues tokens for register and login.
    """
    from .services import verify_otp
    from common.auth import create_token_pair

    if payload.purpose in ("change_password", "forgot_password"):
        return 401, {"message": "Use the dedicated confirm endpoint for this purpose."}

    try:
        otp = await verify_otp(payload.email, payload.otp, payload.purpose)
    except ValueError as e:
        return 401, {"message": str(e)}

    if payload.purpose == "register":
        # Activate the user account
        user = await User.objects.aget(email=payload.email)
        if not user.is_active:
            user.is_active = True
            await user.asave(update_fields=["is_active", "updated_at"])

    elif payload.purpose == "login":
        # Get user from the OTP record
        if not otp.user_id:
            return 401, {"message": "Invalid login session. Please try again."}
        user = await User.objects.aget(pk=otp.user_id)
    else:
        return 401, {"message": "Invalid purpose."}

    # Issue tokens
    tokens = create_token_pair(user)
    return {
        "access": tokens["access"],
        "refresh": tokens["refresh"],
        "token_type": "bearer",
        "user": user,
    }


# ==================== Login ====================


@router.post("/login/", response={200: MessageOut, 401: MessageOut})
async def login(request, payload: UserLogin):
    """
    Authenticate user and send OTP for login verification.
    Returns a message — NOT tokens. User must verify OTP next.
    """
    try:
        user = await User.objects.aget(email=payload.email)
    except User.DoesNotExist:
        return 401, {"message": "Invalid email or password."}

    if not await user.acheck_password(payload.password):
        return 401, {"message": "Invalid email or password."}

    if not user.is_active:
        return 401, {
            "message": "Account is not activated. Please verify your email first."
        }

    # Send OTP for login verification
    try:
        from .services import create_and_send_otp

        await create_and_send_otp(user.email, "login", user=user)
    except ValueError as e:
        return 401, {"message": str(e)}

    return 200, {"message": "OTP sent to your email for login verification."}


# ==================== Resend OTP ====================


@router.post(
    "/resend-otp/", response={200: MessageOut, 401: MessageOut, 429: MessageOut}
)
async def resend_otp(request, payload: ResendOtpIn):
    """Resend OTP for registration or login."""
    from .services import create_and_send_otp

    if payload.purpose == "register":
        if not await User.objects.filter(email=payload.email).aexists():
            return 401, {"message": "Email not registered."}
        user = await User.objects.aget(email=payload.email)
        # Don't allow resend if already active
        if user.is_active:
            return 401, {"message": "Account is already verified. Please login."}
    elif payload.purpose == "login":
        try:
            user = await User.objects.aget(email=payload.email, is_active=True)
        except User.DoesNotExist:
            return 401, {"message": "Invalid email or inactive account."}
    elif payload.purpose == "change_password":
        try:
            user = await User.objects.aget(email=payload.email, is_active=True)
        except User.DoesNotExist:
            return 401, {"message": "Invalid email."}
    elif payload.purpose == "forgot_password":
        try:
            user = await User.objects.aget(email=payload.email, is_active=True)
        except User.DoesNotExist:
            return 401, {"message": "Email not found or account is inactive."}
    else:
        return 401, {"message": "Invalid purpose."}

    try:
        await create_and_send_otp(payload.email, payload.purpose, user=user)
    except ValueError as e:
        return 429, {"message": str(e)}

    return 200, {"message": "New OTP sent to your email."}


# ==================== Refresh Token ====================


@router.post("/refresh/", response={200: RefreshTokenOut, 401: MessageOut})
async def refresh_token(request, payload: RefreshTokenIn):
    """Exchange a refresh token for new access (and optionally refresh) token."""
    from ninja_jwt.tokens import RefreshToken

    try:
        refresh = RefreshToken(payload.refresh)
        user_id = refresh.get("user_id")  # dict-like, no aget()
        if not user_id:
            return 401, {"message": "Invalid refresh token."}

        user = await User.objects.aget(pk=user_id)
        if not user.is_active:
            return 401, {"message": "User account is deactivated."}

        from common.auth import create_token_pair

        tokens = create_token_pair(user)
        return {
            "access": tokens["access"],
            "refresh": tokens["refresh"],
            "token_type": "bearer",
        }
    except Exception:
        return 401, {"message": "Invalid or expired refresh token."}


